//! Embeds the spec files the tests need into wasm32 builds (step 1a.1).
//!
//! WebAssembly has no file system, so `read_spec` cannot read `docs/specs/` there. For a wasm32
//! target this script lists the corpus files (`.kpar` archives and `.kerml`/`.sysml` models) and
//! the few other files in `EXTRA` from `specs.lock.json`, and the spec snippets listed in
//! `snippets/index.json` (step 1a.5, ADR 0016) if they have been extracted, and generates
//! `include_bytes!` entries for them into `OUT_DIR`. The files come from the local, never-committed `docs/specs/` (or
//! `EUREKA_SPECS_DIR`). Nothing is generated into the source tree, and native builds embed nothing.

use serde_json::Value;
use std::fmt::Write as _;
use std::path::PathBuf;

// The same rule the loader uses (`Corpus::from_lock`), so the two cannot disagree.
#[allow(dead_code)]
#[path = "src/files.rs"]
mod files;

/// Spec files the tests read directly, besides the corpus files.
const EXTRA: &[&str] = &[
    "KerML/normative/KerML-Model-Interchange.json", // sysml-corpus: the interchange schema test
    "api/omg/normative/OpenAPI.json",               // sysml-api-types: the OpenAPI examples
];

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let lock_path = manifest.join("../../specs.lock.json");
    println!("cargo:rerun-if-changed={}", lock_path.display());
    println!("cargo:rerun-if-env-changed=EUREKA_SPECS_DIR");
    println!("cargo:rerun-if-changed=src/files.rs");

    let mut code = String::from(
        "// @generated by crates/sysml-corpus/build.rs. Do not edit.\n\
         /// Spec files embedded for wasm32: (path in specs.lock.json, contents).\n\
         pub static FILES: &[(&str, &[u8])] = &[\n",
    );
    if std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("wasm32") {
        let specs = std::env::var_os("EUREKA_SPECS_DIR")
            .map(PathBuf::from)
            .unwrap_or_else(|| manifest.join("../../docs/specs"));
        let lock: Value = serde_json::from_str(&std::fs::read_to_string(&lock_path).unwrap())
            .expect("specs.lock.json is not valid JSON");
        for entry in lock["files"]
            .as_array()
            .expect("specs.lock.json has no files")
        {
            let path = entry["path"].as_str().unwrap_or_default();
            if !(files::is_corpus_file(path)
                || EXTRA.contains(&path)
                || files::is_kerml_library_xmi(path))
            {
                continue;
            }
            let full = specs.join(path).canonicalize().unwrap_or_else(|e| {
                panic!(
                    "{}: {e}. The spec files are not in git. Run `python scripts/fetch_specs.py fetch` first.",
                    specs.join(path).display()
                )
            });
            println!("cargo:rerun-if-changed={}", full.display());
            writeln!(
                code,
                "    ({path:?}, include_bytes!({:?})),",
                full.to_str().unwrap()
            )
            .unwrap();
        }
    }
    if std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("wasm32") {
        let specs = std::env::var_os("EUREKA_SPECS_DIR")
            .map(PathBuf::from)
            .unwrap_or_else(|| manifest.join("../../docs/specs"));
        let index_path = specs.join("snippets/index.json");
        println!("cargo:rerun-if-changed={}", index_path.display());
        // Without the extracted snippets, `snippets()` reports how to extract them.
        if let Ok(index) = std::fs::read_to_string(&index_path) {
            let index: Value = serde_json::from_str(&index).expect("snippets/index.json");
            let mut paths = vec!["index.json".to_owned()];
            for entry in index["snippets"].as_array().into_iter().flatten() {
                paths.push(entry["path"].as_str().unwrap_or_default().to_owned());
            }
            for path in paths {
                let full = specs.join("snippets").join(&path);
                println!("cargo:rerun-if-changed={}", full.display());
                writeln!(
                    code,
                    "    ({:?}, include_bytes!({:?})),",
                    format!("snippets/{path}"),
                    full.canonicalize()
                        .unwrap_or_else(|e| panic!(
                            "{}: {e}. The snippets are incomplete: run `python scripts/extract_spec_snippets.py`.",
                            full.display()
                        ))
                        .to_str()
                        .unwrap()
                )
                .unwrap();
            }
        }
    }
    code.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("embedded_specs.rs");
    std::fs::write(out, code).expect("cannot write embedded_specs.rs");
}
