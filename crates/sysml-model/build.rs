//! Generates metaclass and enumeration definitions from the normative `SysML.json`
//! (SysML v2.0, metamodel 20250201; a superset of KerML.json).
//!
//! The JSON schema is not stored in git. It is fetched into `docs/specs/` by
//! `python scripts/fetch_specs.py fetch`. Set `EUREKA_SPECS_DIR` to use another location.
//!
//! How the schema is laid out (checked by `scripts/check_schema_assumptions.py`):
//! - 175 metaclass definitions. A metaclass with subtypes is `anyOf: [ <object>, $ref Subtype... ]`.
//!   A leaf metaclass is a plain object.
//! - 7 enumerations (`{"type":"string","enum":[...]}`), and `Identified` (`{"@id"}` reference).
//! - Property shapes: `Identified` refs (with the target metaclass IRI in `$comment`),
//!   `oneOf [X, null]`, arrays, and primitive types (boolean, string, integer, number, uuid).

use serde_json::{Map, Value};
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-env-changed=EUREKA_SPECS_DIR");
    let specs_dir = std::env::var_os("EUREKA_SPECS_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../docs/specs")
        });
    let schema_path = specs_dir.join("normative/SysML.json");
    println!("cargo:rerun-if-changed={}", schema_path.display());

    let text = std::fs::read_to_string(&schema_path).unwrap_or_else(|e| {
        panic!(
            "cannot read {}: {e}\nThe spec files are not in git. Run `python scripts/fetch_specs.py fetch` first.",
            schema_path.display()
        )
    });
    let root: Value = serde_json::from_str(&text).expect("SysML.json is not valid JSON");
    let defs = root["$defs"].as_object().expect("SysML.json has no $defs");

    let mut metaclasses: Vec<&str> = Vec::new();
    let mut enums: Vec<(&str, Vec<&str>)> = Vec::new();
    for (name, def) in defs {
        if let Some(lits) = def.get("enum").and_then(Value::as_array) {
            enums.push((name, lits.iter().map(|v| v.as_str().unwrap()).collect()));
        } else if name != "Identified" {
            metaclasses.push(name);
        }
    }
    metaclasses.sort_unstable();
    enums.sort_unstable_by_key(|e| e.0);

    let mut out = String::new();
    out.push_str("// @generated by crates/sysml-model/build.rs from SysML.json. Do not edit.\n\n");

    // ---- enumerations ----
    for (name, lits) in &enums {
        writeln!(out, "/// SysML/KerML enumeration `{name}`.").unwrap();
        out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\n");
        writeln!(out, "pub enum {name} {{").unwrap();
        for l in lits {
            writeln!(out, "    /// `{l}`\n    {},", pascal(l)).unwrap();
        }
        out.push_str("}\n");
        writeln!(out, "impl {name} {{").unwrap();
        writeln!(out, "    /// All literals, in specification order.\n    pub const ALL: &'static [{name}] = &[{}];",
            lits.iter().map(|l| format!("{name}::{}", pascal(l))).collect::<Vec<_>>().join(", ")).unwrap();
        out.push_str(
            "    /// The literal as written in the JSON serialization and the textual notation.\n",
        );
        out.push_str("    pub const fn as_str(self) -> &'static str {\n        match self {\n");
        for l in lits {
            writeln!(out, "            {name}::{} => \"{l}\",", pascal(l)).unwrap();
        }
        out.push_str("        }\n    }\n");
        out.push_str("    /// Parse a literal. Returns `None` if `s` is not a literal of this enumeration.\n");
        out.push_str("    pub fn parse(s: &str) -> Option<Self> {\n        match s {\n");
        for l in lits {
            writeln!(out, "            \"{l}\" => Some({name}::{}),", pascal(l)).unwrap();
        }
        out.push_str("            _ => None,\n        }\n    }\n}\n\n");
    }

    // ---- metaclasses ----
    out.push_str("/// Every metaclass of the SysML v2 abstract syntax, including the KerML metaclasses it reuses.\n");
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum Metaclass {\n");
    for m in &metaclasses {
        writeln!(out, "    /// `{m}`\n    {m},").unwrap();
    }
    out.push_str("}\n\n");

    let mut names = String::new();
    let mut parse = String::new();
    let mut subtypes = String::new();
    let mut props = String::new();
    for m in &metaclasses {
        let def = defs[*m].as_object().unwrap();
        let (obj, subs) = split_any_of(def);
        writeln!(names, "            Metaclass::{m} => \"{m}\",").unwrap();
        writeln!(parse, "            \"{m}\" => Some(Metaclass::{m}),").unwrap();
        writeln!(
            subtypes,
            "            Metaclass::{m} => &[{}],",
            subs.iter()
                .map(|s| format!("Metaclass::{s}"))
                .collect::<Vec<_>>()
                .join(", ")
        )
        .unwrap();

        let properties = obj["properties"]
            .as_object()
            .expect("metaclass without properties");
        let required: Vec<&str> = obj
            .get("required")
            .and_then(Value::as_array)
            .map(|a| a.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let mut items = Vec::new();
        for (pname, pschema) in properties {
            if pname == "@id" || pname == "@type" {
                continue;
            }
            let (kind, many, nullable) = classify(pschema)
                .unwrap_or_else(|| panic!("unrecognized schema for {m}.{pname}: {pschema}"));
            items.push(format!(
                "PropertyDef {{ name: \"{pname}\", kind: {kind}, many: {many}, nullable: {nullable}, required: {} }}",
                required.contains(&pname.as_str())
            ));
        }
        writeln!(
            props,
            "            Metaclass::{m} => &[\n                {}\n            ],",
            items.join(",\n                ")
        )
        .unwrap();
    }

    write!(
        out,
        r#"impl Metaclass {{
    /// All metaclasses, sorted by name.
    pub const ALL: &'static [Metaclass] = &[{all}];

    /// The metaclass name, as used in `@type` in the JSON serialization.
    pub const fn name(self) -> &'static str {{
        match self {{
{names}        }}
    }}

    /// Look up a metaclass by its `@type` name.
    pub fn parse(s: &str) -> Option<Self> {{
        match s {{
{parse}            _ => None,
        }}
    }}

    /// The direct subtypes listed in the schema (`anyOf`).
    pub fn direct_subtypes(self) -> &'static [Metaclass] {{
        match self {{
{subtypes}        }}
    }}

    /// The serialized properties (owned and inherited), excluding `@id` and `@type`.
    pub fn properties(self) -> &'static [PropertyDef] {{
        match self {{
{props}        }}
    }}
}}
"#,
        all = metaclasses
            .iter()
            .map(|m| format!("Metaclass::{m}"))
            .collect::<Vec<_>>()
            .join(", "),
    )
    .unwrap();

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("generated.rs");
    std::fs::write(&dest, out).expect("cannot write generated code");
}

/// Split `anyOf: [object, $ref...]` into the object schema and its direct subtypes.
fn split_any_of(def: &Map<String, Value>) -> (&Map<String, Value>, Vec<String>) {
    match def.get("anyOf").and_then(Value::as_array) {
        Some(parts) => {
            let obj = parts[0]
                .as_object()
                .expect("anyOf[0] must be the object schema");
            let subs = parts[1..]
                .iter()
                .map(|p| last_segment(p["$ref"].as_str().unwrap()).to_string())
                .collect();
            (obj, subs)
        }
        None => (def, Vec::new()),
    }
}

/// Returns (kind expression, many, nullable) for a property schema.
fn classify(s: &Value) -> Option<(String, bool, bool)> {
    if let Some(alts) = s.get("oneOf").and_then(Value::as_array) {
        let non_null: Vec<&Value> = alts
            .iter()
            .filter(|a| a.get("type").and_then(Value::as_str) != Some("null"))
            .collect();
        if non_null.len() != 1 || non_null.len() == alts.len() {
            return None;
        }
        let (k, many, _) = classify(non_null[0])?;
        return Some((k, many, true));
    }
    if s.get("type").and_then(Value::as_str) == Some("array") {
        let (k, _, _) = classify(&s["items"])?;
        return Some((k, true, false));
    }
    if let Some(r) = s.get("$ref").and_then(Value::as_str) {
        let target = last_segment(r);
        if target == "Identified" {
            let to = s
                .get("$comment")
                .and_then(Value::as_str)
                .map(last_segment)
                .unwrap_or("Element");
            return Some((
                format!("PropertyKind::Reference {{ target: \"{to}\" }}"),
                false,
                false,
            ));
        }
        return Some((
            format!("PropertyKind::Enumeration {{ name: \"{target}\" }}"),
            false,
            false,
        ));
    }
    let kind = match (
        s.get("type").and_then(Value::as_str)?,
        s.get("format").and_then(Value::as_str),
    ) {
        ("string", Some("uuid")) => "PropertyKind::Uuid",
        ("string", _) => "PropertyKind::String",
        ("boolean", _) => "PropertyKind::Boolean",
        ("integer", _) => "PropertyKind::Integer",
        ("number", _) => "PropertyKind::Real",
        _ => return None,
    };
    Some((kind.to_string(), false, false))
}

fn last_segment(iri: &str) -> &str {
    iri.rsplit('/').next().unwrap_or(iri)
}

/// `inout` -> `Inout`, `timeslice` -> `Timeslice`.
fn pascal(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}
